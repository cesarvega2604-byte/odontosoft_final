-- Ejecutar el archivo completo en Query Tool, conectado a odontosoft_demo.
-- Conserva las facturas existentes y no programa correos retroactivos.
BEGIN;
SET LOCAL search_path TO public, pg_catalog;
DO $guard$
BEGIN
    IF current_database() <> 'odontosoft_demo' THEN
        RAISE EXCEPTION 'Abre Query Tool en la base odontosoft_demo.';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = to_regclass('public.correo_programado')
          AND attname = 'ultimo_envio' AND NOT attisdropped
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = to_regclass('public.paciente')
          AND attname = 'tipo_documento' AND NOT attisdropped
    ) THEN
        RAISE EXCEPTION 'Aplica primero migracion_identificacion_cumpleanos.sql.';
    END IF;
END
$guard$;

-- Esquema de Mi tratamiento y Facturación.
CREATE TABLE IF NOT EXISTS fase_tratamiento (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente integer NOT NULL REFERENCES paciente(id_paciente) ON DELETE CASCADE,
    id_odontologo integer REFERENCES odontologo(id_odontologo) ON DELETE SET NULL,
    titulo varchar(100) NOT NULL,
    descripcion text NOT NULL,
    pieza integer,
    estado varchar(12) NOT NULL DEFAULT 'pendiente',
    compartida boolean NOT NULL DEFAULT false,
    actualizada_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_fase_tratamiento_estado CHECK (estado IN ('pendiente', 'en_curso', 'completada')),
    CONSTRAINT ck_fase_tratamiento_pieza CHECK (pieza IS NULL OR (pieza BETWEEN 11 AND 48 AND pieza % 10 BETWEEN 1 AND 8))
);
CREATE INDEX IF NOT EXISTS ix_fase_tratamiento_id_paciente ON fase_tratamiento (id_paciente);

CREATE TABLE IF NOT EXISTS compra_servicio (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente integer REFERENCES paciente(id_paciente) ON DELETE SET NULL,
    id_tratamiento integer REFERENCES tratamiento(id_tratamiento) ON DELETE SET NULL,
    concepto varchar(100) NOT NULL,
    cliente varchar(201) NOT NULL,
    precio numeric(10, 2) NOT NULL,
    clave varchar(36) NOT NULL,
    solicitada_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_compra_paciente_clave UNIQUE (id_paciente, clave),
    CONSTRAINT ck_compra_precio CHECK (precio > 0)
);
CREATE INDEX IF NOT EXISTS ix_compra_servicio_id_paciente ON compra_servicio (id_paciente);

ALTER TABLE pago ALTER COLUMN id_cita DROP NOT NULL;
ALTER TABLE pago ADD COLUMN IF NOT EXISTS id_compra integer UNIQUE REFERENCES compra_servicio(id) ON DELETE RESTRICT;
ALTER TABLE pago DROP CONSTRAINT IF EXISTS ck_pago_origen;
ALTER TABLE pago ADD CONSTRAINT ck_pago_origen CHECK ((id_cita IS NULL) <> (id_compra IS NULL));

ALTER TABLE factura ALTER COLUMN id_pago DROP NOT NULL;
ALTER TABLE factura DROP CONSTRAINT IF EXISTS factura_id_pago_fkey;
ALTER TABLE factura ADD CONSTRAINT factura_id_pago_fkey FOREIGN KEY (id_pago) REFERENCES pago(id_pago) ON DELETE SET NULL;
ALTER TABLE factura ADD COLUMN IF NOT EXISTS id_paciente integer REFERENCES paciente(id_paciente) ON DELETE SET NULL;
ALTER TABLE factura ADD COLUMN IF NOT EXISTS emitida_en timestamptz;
ALTER TABLE factura ADD COLUMN IF NOT EXISTS cliente varchar(201);
ALTER TABLE factura ADD COLUMN IF NOT EXISTS concepto text;
ALTER TABLE factura ADD COLUMN IF NOT EXISTS metodo_pago varchar(50);
ALTER TABLE factura ADD COLUMN IF NOT EXISTS fecha_pago date;
ALTER TABLE factura ADD COLUMN IF NOT EXISTS solicitada_en timestamptz;
CREATE INDEX IF NOT EXISTS ix_factura_id_paciente ON factura (id_paciente);

UPDATE factura f
SET id_paciente = c.id_paciente, cliente = concat_ws(' ', pa.nombre, pa.apellido),
    concepto = COALESCE((
        SELECT string_agg(t.nombre, ', ' ORDER BY t.nombre)
        FROM cita_tratamiento ct JOIN tratamiento t ON t.id_tratamiento = ct.id_tratamiento
        WHERE ct.id_cita = c.id_cita
    ), 'Servicio odontológico'),
    metodo_pago = p.metodo_pago, fecha_pago = p.fecha_pago
FROM pago p JOIN cita c ON c.id_cita = p.id_cita JOIN paciente pa ON pa.id_paciente = c.id_paciente
WHERE p.id_pago = f.id_pago AND f.concepto IS NULL;

ALTER TABLE correo_programado ADD COLUMN IF NOT EXISTS id_factura integer
    CONSTRAINT uq_correo_factura UNIQUE REFERENCES factura(id_factura) ON DELETE CASCADE;
ALTER TABLE correo_programado DROP CONSTRAINT IF EXISTS ck_correo_destino;
ALTER TABLE correo_programado ADD CONSTRAINT ck_correo_destino CHECK (
    (tipo IN ('bienvenida', 'cumpleanos') AND id_usuario IS NOT NULL AND id_cita IS NULL AND id_factura IS NULL)
    OR (tipo IN ('cita', 'recordatorio_24h', 'recordatorio_1h', 'encuesta') AND id_cita IS NOT NULL AND id_usuario IS NULL AND id_factura IS NULL)
    OR (tipo = 'factura' AND id_factura IS NOT NULL AND id_usuario IS NULL AND id_cita IS NULL)
);

COMMIT;
