BEGIN;

CREATE TABLE IF NOT EXISTS encuesta_cita (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita integer UNIQUE REFERENCES cita(id_cita) ON DELETE SET NULL,
    token_hash varchar(64) UNIQUE,
    vence timestamptz,
    respondida timestamptz,
    estrellas integer,
    comentario varchar(600),
    CONSTRAINT ck_encuesta_respuesta CHECK (
        (respondida IS NULL AND estrellas IS NULL AND comentario IS NULL)
        OR (respondida IS NOT NULL AND estrellas IS NOT NULL AND comentario IS NOT NULL AND estrellas BETWEEN 1 AND 5)
    )
);

ALTER TABLE correo_programado DROP CONSTRAINT IF EXISTS ck_correo_destino;
ALTER TABLE correo_programado ADD CONSTRAINT ck_correo_destino CHECK (
    (tipo IN ('bienvenida', 'cumpleanos') AND id_usuario IS NOT NULL AND id_cita IS NULL)
    OR (tipo IN ('cita', 'recordatorio_24h', 'recordatorio_1h', 'encuesta') AND id_cita IS NOT NULL AND id_usuario IS NULL)
);

COMMIT;
