BEGIN;

CREATE TABLE IF NOT EXISTS producto (
    id_producto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    descripcion text NOT NULL,
    precio numeric(12, 2) NOT NULL CONSTRAINT ck_producto_precio CHECK (precio >= 0),
    imagen bytea
);

CREATE TABLE IF NOT EXISTS correo_programado (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(24) NOT NULL,
    id_usuario integer REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    id_cita integer REFERENCES cita(id_cita) ON DELETE CASCADE,
    programado_para timestamptz NOT NULL,
    vence timestamptz NOT NULL,
    estado varchar(12) NOT NULL DEFAULT 'pendiente',
    intentos integer NOT NULL DEFAULT 0,
    CONSTRAINT uq_correo_usuario_tipo UNIQUE (id_usuario, tipo),
    CONSTRAINT uq_correo_cita_tipo UNIQUE (id_cita, tipo),
    CONSTRAINT ck_correo_destino CHECK (
        (tipo = 'bienvenida' AND id_usuario IS NOT NULL AND id_cita IS NULL) OR
        (tipo IN ('cita', 'recordatorio_24h', 'recordatorio_1h') AND id_cita IS NOT NULL AND id_usuario IS NULL)
    )
);
CREATE INDEX IF NOT EXISTS ix_correo_programado_pendiente ON correo_programado (estado, programado_para);

-- Agenda futura de instalaciones anteriores. El indicador antiguo ya registra el aviso previo a un día.
WITH futuras AS (
    SELECT id_cita, (fecha + hora) AT TIME ZONE 'America/Bogota' AS inicio, recordatorio_enviado
    FROM cita WHERE lower(trim(estado)) IN ('pendiente', 'en espera', 'confirmada', 'confirmado', 'reprogramada')
      AND fecha >= (now() AT TIME ZONE 'America/Bogota')::date
)
INSERT INTO correo_programado (tipo, id_cita, programado_para, vence)
SELECT aviso.tipo, c.id_cita, c.inicio - aviso.anticipacion, c.inicio - aviso.cierre
FROM futuras c CROSS JOIN (VALUES
    ('recordatorio_24h', interval '24 hours', interval '1 hour'),
    ('recordatorio_1h', interval '1 hour', interval '0 hours')
) AS aviso(tipo, anticipacion, cierre)
WHERE c.inicio - aviso.anticipacion > now()
  AND (aviso.tipo <> 'recordatorio_24h' OR NOT c.recordatorio_enviado)
ON CONFLICT (id_cita, tipo) DO NOTHING;

COMMIT;
