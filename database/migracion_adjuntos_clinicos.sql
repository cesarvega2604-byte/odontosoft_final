BEGIN;
SET LOCAL search_path TO public, pg_catalog;

CREATE TABLE IF NOT EXISTS adjunto_clinico (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente integer NOT NULL REFERENCES paciente(id_paciente) ON DELETE CASCADE,
    id_usuario integer REFERENCES usuario(id_usuario) ON DELETE SET NULL,
    nombre varchar(180) NOT NULL,
    tipo varchar(40) NOT NULL,
    tamano integer NOT NULL,
    creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    contenido bytea NOT NULL,
    CONSTRAINT ck_adjunto_clinico_tamano CHECK (tamano BETWEEN 1 AND 15728640)
);
CREATE INDEX IF NOT EXISTS ix_adjunto_clinico_id_paciente ON adjunto_clinico (id_paciente);

COMMIT;
